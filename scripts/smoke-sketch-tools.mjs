// The sketch's editing tools, in headless Chrome: offset, extend, and the linear and circular patterns, with the one
// dimension each shows driving the rest, kept when the sketch is closed and opened again.
// Usage: node scripts/smoke-sketch-tools.mjs <url> <screenshot folder>
import puppeteer from 'puppeteer-core';
import { mkdirSync } from 'node:fs';

const url = process.argv[2] ?? 'http://localhost:5183/';
const out = process.argv[3] ?? '/tmp/schmishape-sketch-tools';
mkdirSync(out, { recursive: true });

const browser = await puppeteer.launch({
  executablePath: process.env.CHROME ?? '/usr/bin/google-chrome',
  headless: 'new',
  args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'],
  defaultViewport: { width: 1440, height: 900 },
});
const page = await browser.newPage();
const problems = [];
page.on('console', (m) => { if (m.type() === 'error') problems.push(`console: ${m.text()}`); });
page.on('pageerror', (e) => problems.push(`page: ${e.message}`));

let passed = 0;
const failures = [];
const check = (name, ok, detail = '') => {
  if (ok) { passed++; console.log(`  ok   ${name}${detail ? `  (${detail})` : ''}`); }
  else { failures.push(name); console.log(`  FAIL ${name}  ${detail}`); }
};
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const shot = (name) => page.screenshot({ path: `${out}/${name}.png` });
const settle = async (ms = 250) => { await wait(ms); await page.waitForFunction(() => !document.querySelector('.spinner')); await wait(60); };
const cmd = (id) => page.$eval(`[data-command="${id}"]`, (e) => e.click());
const press = async (key, mods = []) => {
  for (const m of mods) await page.keyboard.down(m);
  await page.keyboard.press(key);
  for (const m of mods.reverse()) await page.keyboard.up(m);
  await wait(60);
};
const sketchAt = (x, y) => page.evaluate((x, y) => { const s = window.schmishape.session(); const b = document.querySelector('[data-testid=viewport]').getBoundingClientRect(); const p = s.screen([x, y]); return [p[0] + b.left, p[1] + b.top]; }, x, y);
const moveTo = async (x, y) => { const [sx, sy] = await sketchAt(x, y); await page.mouse.move(sx, sy); await wait(40); };
const clickSketch = async (x, y) => { const [sx, sy] = await sketchAt(x, y); await page.mouse.move(sx, sy); await wait(30); await page.mouse.down(); await page.mouse.up(); await wait(60); };
/** Waits for the sketch's queued edits, then reads it. */
const sketch = () => page.evaluate(async () => {
  const s = window.schmishape.session();
  const d = await s.settled();
  return { entities: d.entities, constraints: d.constraints, links: s.links, analysis: s.analysis[0]() };
});
const near = (a, b, tol = 1e-6) => Math.abs(a - b) < tol;
const nearP = (p, q, tol = 1e-6) => !!p && near(p[0], q[0], tol) && near(p[1], q[1], tol);
/** Types into a field as a person would: all of what's there replaced, then left. */
